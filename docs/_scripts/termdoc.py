"""Generate the consequence terms reference page from the consequence catalogue.

The page lists the same rows as ``vep catalogue show`` (terms) and ``vep catalogue show --subject
facts``: the rows come from that command's own runner, so the reference always matches what the
command prints. The script renders the Markdown itself because rule expressions contain ``|``,
which has to be escaped inside a Markdown table cell.

It also writes the graphs of ``vep catalogue show --graph`` (every term's rule and the catalogue
overview, as an HTML page) and ``vep catalogue show --subject facts --graph`` (the fact
dependencies, as SVG) to a static directory, which the page links to.

Usage: ``python docs/_scripts/termdoc.py [OUTPUT_FILE] [--static_dir DIR]``
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Sequence
from pathlib import Path

from ensembl.vep.config import Config
from ensembl.vep.runner.catalogue.show import FACT_HEADERS, TERM_HEADERS
from ensembl.vep.runner.catalogue.show import Runner as CatalogueShowRunner

INTRODUCTION = """\
(consequence-terms)=
# Consequence terms

The [Sequence Ontology](https://www.sequenceontology.org/) (SO) terms Ensembl VEP can assign to a
variant, in severity order, and the facts their rules are written over. This page is generated by
`make termdoc` from the consequence catalogue, and lists the same rows as `vep catalogue show`.
See [Consequence annotation](../../concepts/consequence_annotation.md) for how the rules are
evaluated.
"""

# Where the graphs are served from, relative to the generated page, and their file names.
STATIC_URL = "../../_static/catalogue"
CATALOGUE_GRAPH = "catalogue.html"
FACTS_GRAPH = "fact_dependencies.svg"

TERMS_INTRODUCTION = """\
Each term is assigned when its rule (the **When** column) is true for a variant allele and the
feature it overlaps. Rank 1 is the most severe term. When a rule is true, the terms it subsumes are
removed from the result, so only the most specific terms are reported. A term without a rule is a
fallback the annotators do not evaluate.

<a href="{static_url}/{catalogue_graph}">See the graph visualisation</a> of every term's rule,
followed by an overview of the whole catalogue in which each term links to its rule. The same page
is written by `vep catalogue show --graph --output_file catalogue.html`.
"""

FACTS_INTRODUCTION = """\
A fact is a named property of one variant allele against one feature, such as `overlap_cds`. Rules
combine facts with `&` (and), `|` (or) and `!` (not). The cost tier orders facts from cheapest to
most expensive to compute. **Deps** lists the facts that must be computed first, and **Requires**
lists the facts that must be true for this fact to be true.

<a href="{static_url}/{facts_graph}">See the fact dependency graph</a>, written by
`vep catalogue show --subject facts --graph`.
"""


def _cell(value: object) -> str:
    """Return one table cell, escaped for Markdown and with code spans where they help."""
    text = str(value).replace("|", "\\|").replace("\n", " ")
    return text


def _code(value: object) -> str:
    """Return a non-empty cell as inline code, or a dash for an empty one."""
    text = str(value)
    if not text:
        return "–"
    return f"`{_cell(text)}`"


def _table(headers: Sequence[str], rows: Sequence[Sequence[object]], code_columns: set[int]) -> list[str]:
    """Return a Markdown pipe table, with the given column indexes rendered as inline code."""
    lines = ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
    for row in rows:
        cells = [_code(cell) if index in code_columns else _cell(cell) for index, cell in enumerate(row)]
        lines.append("| " + " | ".join(cells) + " |")
    return lines


def _runner(subject: str, graph: bool = False) -> CatalogueShowRunner:
    """Return the ``vep catalogue show`` runner for one subject."""
    return CatalogueShowRunner(Config.for_command("catalogue.show", subject=subject, graph=graph))


def _rows(subject: str) -> list[tuple[object, ...]]:
    """Return the rows ``vep catalogue show --subject SUBJECT`` prints."""
    runner = _runner(subject)
    if subject == "facts":
        return runner._fact_rows()  # pylint: disable=protected-access
    return runner._term_rows()  # pylint: disable=protected-access


def render() -> str:
    """Return the consequence terms reference page."""
    term_rows = _rows("terms")
    fact_rows = _rows("facts")
    lines = [
        INTRODUCTION,
        "## Terms",
        "",
        TERMS_INTRODUCTION.format(static_url=STATIC_URL, catalogue_graph=CATALOGUE_GRAPH),
        # Term and When as code; Rank, Accession and Impact as plain text.
        *_table(TERM_HEADERS, term_rows, code_columns={1, 4}),
        "",
        "## Facts",
        "",
        FACTS_INTRODUCTION.format(static_url=STATIC_URL, facts_graph=FACTS_GRAPH),
        *_table(FACT_HEADERS, fact_rows, code_columns={0, 2, 3}),
        "",
    ]
    return "\n".join(lines)


def write_graphs(static_dir: Path) -> None:
    """Write the catalogue page and the fact dependency graph that ``vep catalogue show --graph`` draws."""
    static_dir.mkdir(parents=True, exist_ok=True)
    for subject, file_name in (("terms", CATALOGUE_GRAPH), ("facts", FACTS_GRAPH)):
        rendered = _runner(subject, graph=True)._graph("svg")  # pylint: disable=protected-access
        (static_dir / file_name).write_text(rendered, encoding="utf-8")


def main(argv: list[str] | None = None) -> None:
    """Write the consequence terms page."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument(
        "output_file",
        nargs="?",
        type=Path,
        default=Path("docs/auto/reference/consequence_terms.md"),
        help="where to write",
    )
    parser.add_argument(
        "--static_dir",
        type=Path,
        default=Path("docs/auto/static/catalogue"),
        help="where to write the graphs",
    )
    args = parser.parse_args(argv)
    output_file: Path = args.output_file
    output_file.parent.mkdir(parents=True, exist_ok=True)
    output_file.write_text(render(), encoding="utf-8")
    write_graphs(args.static_dir)
    print(f"termdoc: wrote {output_file}", file=sys.stderr)


if __name__ == "__main__":
    main()
